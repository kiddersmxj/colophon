"""Pointer skills: generated from a skill doc's trigger, never edited by hand."""

from __future__ import annotations

import json
import re

# The line that marks a skill as Colophon's. `skills sync` only ever replaces or
# removes a skill that carries it.
MARK = "<!-- Generated by colophon. Do not edit: `colophon skills sync` overwrites it. -->"

# Characters that would end or change a plain YAML scalar.
_UNSAFE = re.compile(r"(: |\s#|^[\s\-?:,\[\]{}#&*!|>'\"%@`])|[\n\r\t]|\s$|:$")


def _yaml_value(s: str) -> str:
    if _UNSAFE.search(s):
        return json.dumps(s, ensure_ascii=False)
    return s


def pointer(name: str, project: str, title: str, trigger: str, server: str) -> str:
    """The SKILL.md for a skill doc. Its name is the doc's."""
    server = server.rstrip("/")
    return (
        "---\n"
        f"name: {name}\n"
        f"description: {_yaml_value(trigger)}\n"
        "---\n"
        "\n"
        f"{MARK}\n"
        "\n"
        f"# {name}\n"
        "\n"
        f"How to use {title} is kept in Colophon. Fetch the doc and follow it:\n"
        "\n"
        "```sh\n"
        f"curl -s {server}/{project}/{name}.md\n"
        "```\n"
        "\n"
        "Fetch it every time rather than working from memory; it is the current version.\n"
    )


def is_generated(text: str) -> bool:
    return MARK in text
